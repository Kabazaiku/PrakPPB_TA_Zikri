-- PERINGATAN: dua baris drop menghapus tabel lama beserta datanya.
drop table if exists vehicles;
drop table if exists brands;

create table brands (
  id bigint generated by default as identity primary key,
  name text not null,
  country text,
  description text,
  logo_url text            -- URL atau path relatif, mis. assets/logos/honda.svg
);
create table vehicles (
  id bigint generated by default as identity primary key,
  brand_id bigint not null references brands(id) on delete cascade,
  name text not null,
  category text not null check (category in ('Motor','Sepeda','Sepeda Listrik')),
  type text not null,
  price bigint not null,
  description text,
  image_url text,
  specs jsonb not null default '{}'
);

alter table brands enable row level security;
alter table vehicles enable row level security;
create policy "brands_read" on brands for select using (true);
create policy "vehicles_read" on vehicles for select using (true);

